/** Icon for a file in the tree, by extension. */
export function fileIconName(path: string): IconName {
  const ext = path.slice(path.lastIndexOf(".") + 1).toLowerCase();
  switch (ext) {
    case "tex":
    case "ltx":
      return "tex";
    case "bib":
    case "bbl":
      return "bib";
    case "png":
    case "jpg":
    case "jpeg":
    case "gif":
    case "svg":
    case "webp":
    case "bmp":
    case "eps":
      return "image";
    case "pdf":
      return "pdf";
    case "sty":
    case "cls":
    case "bst":
    case "lua":
    case "def":
    case "cfg":
      return "code";
    case "zip":
      return "zip";
    case "md":
      return "markdown";
    default:
      return "file";
  }
}
